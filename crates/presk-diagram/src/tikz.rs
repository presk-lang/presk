//! One view of the diagram as TikZ, for the report: the positions of the
//! layout in points, y down as in the SVG and the page; the formulas the
//! printer's LaTeX, each shrunk into its box when it is wider (`\prfit`),
//! with the reference's macros `\code` and `\den` provided when the
//! document has none.

use std::fmt::Write;

use crate::layout::{View, numbers, title};
use crate::{Kind, Network};

/// The colours of the realized types, as the SVG's.
const COLOURS: [(&str, &str); 6] = [("f64", "3567B5"), ("f32", "2E8B57"), ("bf16", "C0392B"), ("int", "7B52AB"), ("idx", "8E6C2A"), ("other", "606060")];

fn colour(dtype: &str) -> &'static str {
    match dtype {
        "f64" => "pkf64",
        "f32" => "pkf32",
        "bf16" => "pkbf16",
        "int8" | "int4" => "pkint",
        "idx" | "bool" => "pkidx",
        _ => "pkother",
    }
}

/// Text for a TikZ node: TeX's specials escaped.
fn esc(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\textbackslash{}"),
            '{' | '}' | '%' | '$' | '&' | '#' | '_' => {
                o.push('\\');
                o.push(c);
            }
            '^' => o.push_str("\\^{}"),
            '~' => o.push_str("\\~{}"),
            // Signs a typewriter font may not have, as mathematics.
            c if greek(c).is_some() => {
                let _ = write!(o, "$\\{}$", greek(c).unwrap_or_default());
            }
            '×' => o.push_str("$\\times$"),
            '·' => o.push_str("$\\cdot$"),
            'ℓ' => o.push_str("$\\ell$"),
            '—' => o.push_str("---"),
            c => o.push(c),
        }
    }
    o
}

/// A Greek letter's name in TeX.
fn greek(c: char) -> Option<&'static str> {
    const G: [(char, &str); 16] = [('α', "alpha"), ('β', "beta"), ('γ', "gamma"), ('δ', "delta"), ('ε', "varepsilon"), ('η', "eta"), ('θ', "theta"), ('λ', "lambda"), ('μ', "mu"), ('π', "pi"), ('ρ', "rho"), ('σ', "sigma"), ('τ', "tau"), ('φ', "varphi"), ('ψ', "psi"), ('ω', "omega")];
    G.iter().find(|(g, _)| *g == c).map(|(_, n)| *n)
}

/// The preamble a standalone document needs.
pub const PREAMBLE: &str = "\\documentclass[border=4pt]{standalone}\n\\usepackage{amsmath,amssymb,stmaryrd,graphicx}\n\\usepackage{tikz}\n\\begin{document}\n";

/// The view `v` of `net` as a `tikzpicture`, or as a document that compiles
/// alone (LuaLaTeX or XeLaTeX: the labels are Unicode). `command` is written
/// in its first comment, the command that made it.
pub fn tikz(net: &Network, v: &View, standalone: bool, command: &str) -> String {
    let mut s = String::new();
    if standalone {
        s.push_str(PREAMBLE);
    }
    let what = if v.rects.contains_key(&0) { format!("opened at {:?}", v.open) } else { format!("the box `{}` alone", v.open.first().map_or(String::new(), |b| title(&net.nodes[*b]))) };
    let _ = writeln!(s, "% The network of `{}`, {what}: {:.0} × {:.0} pt, the positions of presk-diagram's layout,", net.entry, v.width, v.height);
    let also = if v.rects.contains_key(&0) { "which presk explain's network.svg and page draw too" } else { "which the page draws inside the box opened" };
    let _ = writeln!(s, "% {also} (plan 0.14.0, D143). Generated by:");
    let _ = writeln!(s, "% {command}");
    s.push_str("\\providecommand{\\code}[1]{\\text{\\texttt{#1}}}\n\\providecommand{\\den}[1]{\\llbracket #1 \\rrbracket}\n");
    s.push_str("\\providecommand{\\prfit}[2]{\\sbox0{#2}\\ifdim\\wd0>#1\\resizebox{#1}{!}{\\usebox0}\\else\\usebox0\\fi}\n");
    for (n, h) in COLOURS {
        let _ = writeln!(s, "\\definecolor{{pk{n}}}{{HTML}}{{{h}}}");
    }
    s.push_str("\\begin{tikzpicture}[x=1pt, y=-1pt, every node/.style={inner sep=0pt, outer sep=0pt}, font=\\small\\ttfamily]\n");
    // Boxes first, outermost first; then the arrows; then the nodes.
    let mut ids: Vec<usize> = v.rects.keys().copied().filter(|i| !net.nodes[*i].key).collect();
    ids.sort_by_key(|i| (net.nodes[*i].depth, *i));
    let open = |i: usize| i == 0 || v.open.contains(&i);
    for id in ids.iter().copied().filter(|i| net.nodes[*i].kind.is_box() && open(*i)) {
        let (n, r) = (&net.nodes[id], v.rects[&id]);
        if n.kind != Kind::Root {
            let c = n.params.as_ref().and_then(|p| p.types.first()).map_or("pkother", |t| colour(t));
            let _ = writeln!(s, "\\draw[rounded corners=4pt, draw={c}, line width=0.8pt, fill=white] ({:.1},{:.1}) rectangle ({:.1},{:.1});", r.x, r.y, r.x + r.w, r.y + r.h);
        }
        let _ = writeln!(s, "\\node[anchor=base west] at ({:.1},{:.1}) {{\\textbf{{{}}}}};", r.x + 8.0, r.y + 15.0, esc(&title(n)));
        let _ = writeln!(s, "\\node[anchor=base west, gray] at ({:.1},{:.1}) {{\\scriptsize {}}};", r.x + 8.0, r.y + 29.0, esc(&numbers(n)));
    }
    for (id, pts) in &v.routes {
        let e = &net.edges[*id];
        if e.key || net.nodes[e.from].key || net.nodes[e.to].key {
            continue;
        }
        let w = (0.4 + (e.bytes.max(1) as f64).log10() * 0.18).clamp(0.4, 2.0);
        let mut d = format!("({:.1},{:.1})", pts[0].0, pts[0].1);
        for k in 1..pts.len() {
            let (px, py) = pts[k - 1];
            let (x, y) = pts[k];
            let my = (py + y) / 2.0;
            let _ = write!(d, " .. controls ({px:.1},{my:.1}) and ({x:.1},{my:.1}) .. ({x:.1},{y:.1})");
        }
        let _ = writeln!(s, "\\draw[-latex, draw={}, line width={w:.2}pt] {d};", colour(&e.dtype));
    }
    for id in ids.iter().copied().filter(|i| !(net.nodes[*i].kind.is_box() && open(*i))) {
        let (n, r) = (&net.nodes[id], v.rects[&id]);
        match n.kind {
            Kind::Call | Kind::Stack => {
                let c = n.params.as_ref().and_then(|p| p.types.first()).map_or("pkother", |t| colour(t));
                if n.kind == Kind::Stack {
                    let _ = writeln!(s, "\\draw[rounded corners=4pt, draw={c}, fill=white] ({:.1},{:.1}) rectangle ({:.1},{:.1});", r.x + 4.0, r.y + 4.0, r.x + r.w + 4.0, r.y + r.h + 4.0);
                }
                let _ = writeln!(s, "\\draw[rounded corners=4pt, draw={c}, line width=0.8pt, fill=black!3] ({:.1},{:.1}) rectangle ({:.1},{:.1});", r.x, r.y, r.x + r.w, r.y + r.h);
                let _ = writeln!(s, "\\node[anchor=base west] at ({:.1},{:.1}) {{\\textbf{{{}}}}};", r.x + 8.0, r.y + 15.0, esc(&title(n)));
                let _ = writeln!(s, "\\node[anchor=base west, gray] at ({:.1},{:.1}) {{\\scriptsize {}}};", r.x + 8.0, r.y + 29.0, esc(&numbers(n)));
                if let Some(t) = &n.tex {
                    let _ = writeln!(s, "\\node[anchor=north west] at ({:.1},{:.1}) {{\\prfit{{{:.1}pt}}{{\\scriptsize $\\displaystyle {}$}}}};", r.x + 8.0, r.y + 36.0, (r.w - 16.0).max(10.0), t.replace('\n', " "));
                }
            }
            Kind::Group | Kind::Op | Kind::Host => {
                let dash = if n.kind == Kind::Host { ", dashed" } else { "" };
                let fill = if n.kind == Kind::Group { "orange!12" } else { "white" };
                let _ = writeln!(s, "\\draw[rounded corners={:.1}pt, draw=brown{dash}, fill={fill}] ({:.1},{:.1}) rectangle ({:.1},{:.1});", r.h / 2.0, r.x, r.y, r.x + r.w, r.y + r.h);
                let _ = writeln!(s, "\\node at ({:.1},{:.1}) {{{}}};", r.x + r.w / 2.0, r.y + r.h / 2.0, esc(&n.label));
            }
            Kind::Param => {
                let _ = writeln!(s, "\\draw[rounded corners=2pt, draw=pkint, fill=pkint!8] ({:.1},{:.1}) rectangle ({:.1},{:.1});", r.x, r.y, r.x + r.w, r.y + r.h);
                let _ = writeln!(s, "\\node[anchor=base west] at ({:.1},{:.1}) {{$\\theta$.{}}};", r.x + 6.0, r.y + 14.0, esc(&n.label));
                let line = numbers(n);
                if !line.is_empty() {
                    let _ = writeln!(s, "\\node[anchor=base west, gray] at ({:.1},{:.1}) {{\\scriptsize {}}};", r.x + 6.0, r.y + 28.0, esc(&line));
                }
            }
            Kind::Input | Kind::Output => {
                let _ = writeln!(s, "\\draw[rounded corners={:.1}pt, draw=gray] ({:.1},{:.1}) rectangle ({:.1},{:.1});", r.h / 2.0, r.x, r.y, r.x + r.w, r.y + r.h);
                let _ = writeln!(s, "\\node[gray] at ({:.1},{:.1}) {{{}}};", r.x + r.w / 2.0, r.y + r.h / 2.0, esc(&n.label));
            }
            Kind::Root => {}
        }
    }
    s.push_str("\\end{tikzpicture}\n");
    if standalone {
        s.push_str("\\end{document}\n");
    }
    s
}
