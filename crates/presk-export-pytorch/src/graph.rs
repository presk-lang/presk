//! `presk export --mode graph`: the specification's graph mode in its light
//! form (tool-level interoperability): a driver `export.py` that builds the
//! exported model with the conformance parameters and produces `model.pt2`
//! (`torch.export`) and `model.onnx` (`torch.onnx.export`, dynamo based),
//! in float32. The Presk-native StableHLO path needs solved dtypes and is
//! planned with the precision solver (0.3.0).

use crate::Generated;
use crate::conformance::ConformanceData;

/// `export.py`, for a module entry (`MiniGPT.apply`) with conformance data.
pub fn graph_driver(d: &ConformanceData) -> Option<Generated> {
    let (class, args) = d.class.as_ref()?;
    let a: Vec<String> = args.iter().map(|x| x.to_string()).collect();
    let names: Vec<String> = d.inputs.iter().skip(1).map(|n| format!("{n:?}")).collect();
    let content = format!(
        r#"# Generated by `presk export --mode graph` (entry `{entry}`): the model as
# tool-level graphs. Builds `{class}` with the conformance parameters
# (`conformance/inputs.json`), then saves `model.pt2` (torch.export) and
# `model.onnx` (torch.onnx.export, dynamo), both in float32 with the example
# inputs' shapes. Run `python export.py`; `test_conformance.py` checks the
# ONNX graph under ONNX Runtime against the interpreter's expected output.
import os

import torch

from {module_file} import *
from test_conformance import flatten_params, load, to_value

HERE = os.path.dirname(os.path.abspath(__file__))
INPUTS = [{names}]


def build(dtype=torch.float32):
    inputs = {{k: to_value(v) for k, v in load("inputs.json").items()}}
    model = {class}({args}).to(dtype)
    model.load_state_dict({{k: v.to(dtype) for k, v in flatten_params(inputs["{theta}"], model).items()}})
    model.eval()
    args = tuple(inputs[n].to(dtype) if inputs[n].is_floating_point() else inputs[n] for n in INPUTS)
    return model, args


def export_all():
    model, args = build()
    pt2 = os.path.join(HERE, "model.pt2")
    onnx_path = os.path.join(HERE, "model.onnx")
    with torch.no_grad():
        exported = torch.export.export(model, args)
        torch.export.save(exported, pt2)
        torch.onnx.export(model, args, onnx_path, dynamo=True)
    return {{"pt2": pt2, "onnx": onnx_path}}


if __name__ == "__main__":
    for kind, path in export_all().items():
        print(f"{{kind}}: {{path}}")
"#,
        entry = d.entry,
        module_file = d.module_file,
        names = names.join(", "),
        args = a.join(", "),
        theta = d.inputs.first().map(String::as_str).unwrap_or("θ"),
    );
    Some(Generated { name: "export.py".into(), content })
}
