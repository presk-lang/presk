//! `presk export --serve`: the `inference serve` block as a PyTorch
//! generation loop (`serve.py`) over the exported module, reading the weights
//! from `final.pt` (written by `train.py`) or from a `params M` `.psk.d`
//! checkpoint of `presk train` (through `pskd.py`'s `read_params`, which
//! needs the parameter tree's layout: it is generated into the script).

use presk_types::ty::ParamsTree;

use crate::Generated;

/// What the generated `serve.py` needs to know.
#[derive(Clone, Debug)]
pub struct ServeSpec {
    /// Source file, for the header comment.
    pub source: String,
    /// Python module (stem) defining the model class, the class, and the
    /// names of its constructor's dimension arguments (`T` for `MiniGPT(T)`).
    pub model_stem: String,
    pub class: String,
    pub ctor_dims: Vec<String>,
    /// Python module (stem) of the source file (defines the generation function).
    pub main_stem: String,
    /// The generation function, whether it takes a key before the context
    /// (plan 0.10.0 step 7b), and, when it takes one, its temperature's
    /// default.
    pub generate: Option<String>,
    pub key: bool,
    pub temperature: Option<String>,
    /// The name of the context's `seq` dimension (`T`).
    pub seq_dim: Option<String>,
    /// `weights = "ckpt/final"` as written.
    pub weights: Option<String>,
    /// The parameter tree's layout as a Python literal ([`layout_py`]).
    pub layout: String,
    /// Fields of the block without effect.
    pub ignored: Vec<String>,
}

/// The parameter tree as a Python literal for `pskd.read_params`: a leaf is
/// `None`, a module a dict of its fields in order, `stack{L}(M)` is
/// `["stack", <M's layout>]` (every leaf gets a leading axis of length `L`).
pub fn layout_py(t: &ParamsTree) -> String {
    match t {
        ParamsTree::Leaf(_) => "None".into(),
        ParamsTree::Node(fields) => format!("{{{}}}", fields.iter().map(|(n, sub)| format!("{n:?}: {}", layout_py(sub))).collect::<Vec<_>>().join(", ")),
        ParamsTree::Stacked { inner, .. } => format!("[\"stack\", {}]", layout_py(inner)),
    }
}

/// `pskd.py` and `serve.py`.
pub fn serve_files(spec: &ServeSpec) -> Vec<Generated> {
    vec![Generated { name: "pskd.py".into(), content: crate::train::PSKD_PY.to_string() }, Generated { name: "serve.py".into(), content: serve_py(spec) }]
}

