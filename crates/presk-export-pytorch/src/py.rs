//! The Python printer.

use presk_syntax::ast::{self, Arg, BinOp, ConfigItem, Decl, Expr, IndexSel, Lit, Member, Pat, UnOp};
use presk_syntax::{Diagnostic, SourceMap, Span};
use presk_types::check::{Callee, TypedProgram};
use presk_types::dim::{DimExpr, DimVar, rat};
use presk_types::elab::{ElabProgram, FnId, FnSig};
use presk_types::ty::{ModRef, ModuleId, Shape, Ty};

use crate::{Options, StackMode, stem};

pub(crate) struct Printer<'a> {
    sm: &'a SourceMap,
    elab: &'a ElabProgram,
    typed: &'a TypedProgram,
    opts: &'a Options,
    unit: usize,
    diags: &'a mut Vec<Diagnostic>,
    out: String,
    indent: usize,
    /// The module whose method is being printed (its type parameters are `self.X`).
    module: Option<ModuleId>,
    /// The function being printed.
    fn_id: Option<FnId>,
    /// Dimension variables bound to Python names in the current function
    /// (`T = ids.shape[1]`).
    bound_dims: Vec<(DimVar, String)>,
    /// Module-typed parameters in scope (`net`) and their instance.
    module_params: Vec<(String, ModRef)>,
    /// File dimensions that are constructor arguments of the current module.
    extra: Vec<DimVar>,
    /// Counter for the temporaries of stacked calls hoisted out of expressions.
    temps: usize,
}

impl<'a> Printer<'a> {
    pub(crate) fn new(sm: &'a SourceMap, elab: &'a ElabProgram, typed: &'a TypedProgram, opts: &'a Options, unit: usize, diags: &'a mut Vec<Diagnostic>) -> Self {
        Printer { sm, elab, typed, opts, unit, diags, out: String::new(), indent: 0, module: None, fn_id: None, bound_dims: vec![], module_params: vec![], extra: vec![], temps: 0 }
    }

    fn line(&mut self, s: &str) {
        if s.is_empty() {
            self.out.push('\n');
        } else {
            self.out.push_str(&"    ".repeat(self.indent));
            self.out.push_str(s);
            self.out.push('\n');
        }
    }

    fn error(&mut self, span: Span, msg: impl Into<String>) {
        self.diags.push(Diagnostic::error("E8001", msg).label(span, "not exported"));
    }

    fn loc(&self, span: Span) -> String {
        let f = self.elab.units[self.unit].path.file_name().and_then(|s| s.to_str()).unwrap_or("");
        let (line, _) = self.sm.file(span.file).line_col(span.start);
        format!("{f}:{line}")
    }

    // ----- the file ----------------------------------------------------

    pub(crate) fn unit(&mut self) -> String {
        let u = &self.elab.units[self.unit];
        let name = u.path.display().to_string();
        self.line(&format!("# Generated by `presk export --target pytorch --mode readable` from {name}."));
        self.line("# Do not edit by hand. Structure and names mirror the Presk source; shapes are");
        self.line("# given as comments in Presk notation. Presk's semantics is exact over ℝ; this");
        self.line("# export runs in the dtype of its inputs (float32 by default) and cannot");
        self.line("# guarantee the error budget declared in the source, which is reproduced as a comment.");
        self.line("import math");
        self.line("import torch");
        self.line("import torch.nn as nn");
        self.line("import torch.nn.functional as F");
        for (_, target) in &u.imports {
            self.line(&format!("from {} import *", stem(self.elab, *target)));
        }
        self.line("");
        self.line("");
        self.line("def _split_heads(x, H, HD):");
        self.line("    \"\"\"ℝ[..., seq, model] -> ℝ[..., heads, seq, hd] (Presk's `split_heads`).\"\"\"");
        self.line("    return x.view(*x.shape[:-1], H, HD).transpose(-3, -2)");
        self.line("");
        self.line("");
        self.line("def _merge_heads(x, H, HD):");
        self.line("    \"\"\"ℝ[..., heads, seq, hd] -> ℝ[..., seq, model] (Presk's `merge_heads`).\"\"\"");
        self.line("    return x.transpose(-3, -2).reshape(*x.shape[:-3], x.shape[-2], H * HD)");
        self.line("");
        let decls = u.ast.decls.clone();
        for d in &decls {
            match d {
                Decl::Const { name, .. } => {
                    if let Some(c) = u.consts.get(&name.name) {
                        self.line(&format!("{} = {}", name.name, c.value));
                    }
                }
                Decl::StaticAssert { cond, span } => {
                    let text = self.expr(cond);
                    let _ = span;
                    self.line(&format!("assert {text}, \"static assert {text}\""));
                }
                Decl::Dim { name, bound, .. } => match bound {
                    Some(b) => {
                        let bt = self.expr(b);
                        self.line(&format!("# dim {} <= {bt}  (symbolic; bound checked where the dimension is bound)", name.name));
                    }
                    None => self.line(&format!("# dim {}  (symbolic)", name.name)),
                },
                Decl::TypeAlias { name, ty, .. } => {
                    let t = u.types.get(&name.name).map(|t| t.display(&self.elab.names())).unwrap_or_default();
                    let _ = ty;
                    self.line(&format!("# type {} = {t}", name.name));
                }
                _ => {}
            }
        }
        self.line("");
        for d in &decls {
            match d {
                Decl::Module(m) => {
                    let mid = u.modules[&m.name.name];
                    self.module_decl(mid, m);
                }
                Decl::Fn(f) => {
                    let fid = u.fns[&f.name.name];
                    self.fn_decl(fid, f, false);
                }
                _ => {}
            }
        }
        for d in &decls {
            match d {
                Decl::Optimizer { name, items, .. } => self.config_comment(&format!("optimizer {}", name.name), items),
                Decl::Training { items, .. } => self.config_comment("training run", items),
                Decl::Inference { items, .. } => self.config_comment("inference serve", items),
                _ => {}
            }
        }
        std::mem::take(&mut self.out)
    }

    fn config_comment(&mut self, what: &str, items: &[ConfigItem]) {
        self.line(&format!("# {what} {{  -- not exported in 0.1.0: a training loop or a serving configuration"));
        for it in items {
            match it {
                ConfigItem::Field { name, value, .. } => {
                    let v = self.raw_expr(value);
                    self.line(&format!("#   {} = {v}", name.name));
                }
                ConfigItem::Checkpoint { every, to, .. } => {
                    let e = self.raw_expr(every);
                    self.line(&format!("#   checkpoint every {e} steps to \"{to}\""));
                }
            }
        }
        self.line("# }");
        self.line("");
    }

    // ----- modules -----------------------------------------------------

    /// Dimension variables of the file that a module's parameters (or its
    /// sub-modules' parameters) mention: they become constructor arguments,
    /// since PyTorch needs concrete shapes at construction.
    pub(crate) fn extra_dims(&self, mid: ModuleId) -> Vec<DimVar> {
        fn go(elab: &ElabProgram, mid: ModuleId, out: &mut Vec<DimVar>, seen: &mut Vec<ModuleId>) {
            if seen.contains(&mid) {
                return;
            }
            seen.push(mid);
            let def = elab.module(mid);
            for p in &def.params {
                if let Some(s) = p.ty.shape() {
                    for a in &s.axes {
                        for v in a.len.vars() {
                            if !def.typarams.contains(&v) && !out.contains(&v) {
                                out.push(v);
                            }
                        }
                    }
                }
            }
            for u in &def.uses {
                let mut r = &u.module;
                loop {
                    match r {
                        ModRef::Inst { def: d, args } => {
                            for a in args {
                                for v in a.vars() {
                                    if !def.typarams.contains(&v) && !out.contains(&v) {
                                        out.push(v);
                                    }
                                }
                            }
                            let before = out.len();
                            let mut inner = Vec::new();
                            go(elab, *d, &mut inner, seen);
                            for v in inner {
                                if !def.typarams.contains(&v) && !out.contains(&v) {
                                    out.push(v);
                                }
                            }
                            let _ = before;
                            break;
                        }
                        ModRef::Stack { inner, .. } => r = inner,
                        ModRef::Compose(_) => break,
                    }
                }
            }
        }
        let mut out = Vec::new();
        go(self.elab, mid, &mut out, &mut Vec::new());
        out.sort();
        out
    }

    fn module_decl(&mut self, mid: ModuleId, m: &ast::ModuleDecl) {
        let def = self.elab.module(mid).clone();
        self.module = Some(mid);
        let mut tps: Vec<String> = def.typarams.iter().map(|v| self.elab.dim_name(*v)).collect();
        let extra = self.extra_dims(mid);
        for v in &extra {
            tps.push(self.elab.dim_name(*v));
        }
        self.extra = extra;
        self.line(&format!("class {}(nn.Module):", def.name));
        self.indent += 1;
        self.line(&format!("\"\"\"Generated from `module {}` ({}). Do not edit by hand.\"\"\"", def.name, self.loc(m.span)));
        self.line("");
        let args = if tps.is_empty() { String::new() } else { format!(", {}", tps.join(", ")) };
        self.line(&format!("def __init__(self{args}):"));
        self.indent += 1;
        self.line("super().__init__()");
        for t in &tps {
            self.line(&format!("self.{t} = {t}"));
        }
        for member in &m.members {
            match member {
                Member::Param { names, init, .. } => {
                    for n in names {
                        let Some(p) = def.params.iter().find(|p| p.name == n.name) else { continue };
                        let shape = self.py_shape(p.ty.shape().unwrap(), true);
                        let init_s = match init {
                            None => format!("nn.Parameter(torch.zeros({shape}))"),
                            Some(Expr::Var { path }) => match path.dotted().as_str() {
                                "zeros" => format!("nn.Parameter(torch.zeros({shape}))"),
                                "ones" => format!("nn.Parameter(torch.ones({shape}))"),
                                "xavier_uniform" => format!("nn.init.xavier_uniform_(nn.Parameter(torch.empty({shape})))"),
                                other => format!("nn.Parameter(torch.empty({shape}))  # init = {other}: unknown initializer"),
                            },
                            Some(Expr::Call { args, .. }) => {
                                let std = args.iter().find_map(|a| match a {
                                    Arg::Named { name, value } if name.name == "std" => Some(self.raw_expr(value)),
                                    _ => None,
                                }).unwrap_or_else(|| "1.0".into());
                                format!("nn.init.normal_(nn.Parameter(torch.empty({shape})), std={std})")
                            }
                            Some(_) => format!("nn.Parameter(torch.empty({shape}))"),
                        };
                        let ty = p.ty.display(&self.elab.names());
                        self.line(&format!("self.{} = {init_s}  # {}", n.name, ty));
                    }
                }
                Member::Use { names, .. } => {
                    for n in names {
                        let Some(u) = def.uses.iter().find(|u| u.name == n.name) else { continue };
                        let ctor = self.mod_ctor(&u.module);
                        self.line(&format!("self.{} = {ctor}", n.name));
                    }
                }
                Member::Fn(_) => {}
            }
        }
        self.indent -= 1;
        for member in &m.members {
            if let Member::Fn(f) = member {
                let fid = def.fns.iter().copied().find(|id| self.elab.function(*id).name == f.name.name).unwrap();
                self.line("");
                self.fn_decl(fid, f, true);
            }
        }
        self.indent -= 1;
        self.line("");
        self.module = None;
        self.extra.clear();
    }

    /// The constructor expression of a module reference.
    fn mod_ctor(&mut self, r: &ModRef) -> String {
        match r {
            ModRef::Inst { def, args } => {
                let name = self.elab.module(*def).name.clone();
                let mut a: Vec<String> = args.iter().map(|e| self.dim(e)).collect();
                for v in self.extra_dims(*def) {
                    a.push(self.dim(&DimExpr::var(v)));
                }
                format!("{name}({})", a.join(", "))
            }
            ModRef::Stack { n, inner } => {
                let count = self.dim(n);
                let inner = self.mod_ctor(inner);
                format!("nn.ModuleList([{inner} for _ in range({count})])")
            }
            ModRef::Compose(parts) => {
                let ps: Vec<String> = parts.iter().map(|p| self.mod_ctor(p)).collect();
                format!("nn.Sequential({})", ps.join(", "))
            }
        }
    }

    // ----- functions -----------------------------------------------------

    fn fn_decl(&mut self, fid: FnId, f: &ast::FnDecl, method: bool) {
        let sig: FnSig = self.elab.function(fid).clone();
        self.fn_id = Some(fid);
        self.temps = 0;
        self.bound_dims.clear();
        self.module_params.clear();
        let name = if method && sig.name == "apply" { "forward".to_string() } else { sig.name.clone() };
        let mut params: Vec<String> = if method { vec!["self".into()] } else { vec![] };
        for (i, p) in sig.params.iter().enumerate() {
            if let Some(Ty::Module(r)) = &p.ty {
                self.module_params.push((p.name.clone(), r.clone()));
            }
            let mut s = p.name.clone();
            if let Some(d) = &p.default {
                s.push_str(&format!("={}", self.raw_expr(d)));
            }
            let _ = i;
            params.push(s);
        }
        // The file's dimensions it reads and its arguments do not give, by
        // keyword from its callers (0.17.0 step 6: `angles()` reads `T`).
        let passed = if method { vec![] } else { self.dims_passed(fid) };
        if !passed.is_empty() {
            params.push("*".into());
            for v in &passed {
                let n = self.elab.dim_name(*v);
                params.push(n.clone());
                self.bound_dims.push((*v, n));
            }
        }
        if sig.effects.iter().any(|e| e == "Rand") {
            // A `uses Rand` function takes the switch of `dropout`, off by
            // default and passed on to every `uses Rand` callee; `train.py`
            // turns it on (D54). Its keys are its parameters, as in the
            // program, and read by nothing: PyTorch draws `sample`'s tokens
            // and `dropout`'s masks from its own generator (plan 0.10.0 step
            // 7b, D99).
            params.push("training=False".into());
        }
        if !method {
            let tps: Vec<String> = sig.typarams.iter().chain(&sig.implicit_dims).map(|v| self.elab.dim_name(*v)).collect();
            if !tps.is_empty() {
                self.line(&format!("# dimensions {}: symbolic, taken from the arguments' shapes", tps.join(", ")));
            }
        }
        self.line(&format!("def {name}({}):", params.join(", ")));
        self.indent += 1;
        self.line(&format!("\"\"\"Generated from `fn {}` ({}).\"\"\"", sig.name, self.loc(f.span)));
        // Parameter types as comments; bind symbolic dimensions from shapes.
        for (i, p) in sig.params.iter().enumerate() {
            let Some(ty) = self.typed.param_ty.get(&(fid, i)).cloned().or_else(|| p.ty.clone()) else { continue };
            if matches!(ty, Ty::Module(_)) {
                self.line(&format!("# {} : {}  (a module, passed as an nn.Module)", p.name, ty.display(&self.elab.names())));
                continue;
            }
            self.line(&format!("# {} : {}", p.name, ty.display(&self.elab.names())));
            if let Ty::Tuple(ts) = &ty {
                for (j, t) in ts.iter().enumerate() {
                    if let Some(shape) = t.shape()
                        && shape.prefix.is_none()
                    {
                        for (k, a) in shape.axes.iter().enumerate() {
                            if let Some((v, c)) = affine_var(&a.len)
                                && !self.is_named(v)
                            {
                                let n = self.elab.dim_name(v);
                                self.line(&format!("{n} = {}", less(format!("{}[{j}].shape[{k}]", p.name), c)));
                                self.bound_dims.push((v, n));
                            }
                        }
                    }
                }
            }
            if let Some(shape) = ty.shape().cloned()
                && shape.prefix.is_none()
            {
                for (k, a) in shape.axes.iter().enumerate() {
                    if let Some((v, c)) = affine_var(&a.len)
                        && !self.is_named(v)
                    {
                        let n = self.elab.dim_name(v);
                        self.line(&format!("{n} = {}", less(format!("{}.shape[{k}]", p.name), c)));
                        self.bound_dims.push((v, n));
                    }
                }
                if self.opts.shapes_check {
                    let sh = self.py_shape(&shape, false);
                    self.line(&format!("assert {}.shape == ({sh},), f\"{}: expected {} \" + str(tuple({}.shape))", p.name, p.name, ty.display(&self.elab.names()).replace('"', "'"), p.name));
                }
            }
        }
        self.body(&f.body);
        self.indent -= 1;
        if !method {
            self.line("");
        }
        self.fn_id = None;
    }

    /// The dimensions of its file a top-level function reads, itself or
    /// through the top-level functions it calls, that no closed shape of its
    /// parameters gives: its callers pass them by keyword.
    fn dims_passed(&self, fid: FnId) -> Vec<DimVar> {
        let sig = self.elab.function(fid);
        if sig.owner.is_some() {
            return vec![];
        }
        let file = &self.elab.units[sig.unit].dims;
        let mut used: std::collections::BTreeSet<DimVar> = std::collections::BTreeSet::new();
        let mut calls: Vec<Span> = Vec::new();
        walk_names(&sig.body, &mut |n| {
            if let Some(v) = file.get(n) {
                used.insert(*v);
            }
        }, &mut |sp| calls.push(sp));
        for sp in calls {
            if let Some(Callee::Fn { id, module: None, .. }) = self.typed.callees.get(&sp)
                && *id != fid
            {
                used.extend(self.dims_passed(*id));
            }
        }
        let mut given: std::collections::BTreeSet<DimVar> = std::collections::BTreeSet::new();
        for (i, p) in sig.params.iter().enumerate() {
            let Some(ty) = self.typed.param_ty.get(&(fid, i)).cloned().or_else(|| p.ty.clone()) else { continue };
            let shapes: Vec<Shape> = match &ty {
                Ty::Tuple(ts) => ts.iter().filter_map(|t| t.shape().cloned()).collect(),
                t => t.shape().cloned().into_iter().collect(),
            };
            for sh in shapes.iter().filter(|s| s.prefix.is_none()) {
                given.extend(sh.axes.iter().filter_map(|a| affine_var(&a.len)).map(|(v, _)| v));
            }
        }
        used.into_iter().filter(|v| !given.contains(v)).collect()
    }

    /// Is this dimension variable nameable already (a type parameter, a
    /// module parameter, a constant)?
    fn is_named(&self, v: DimVar) -> bool {
        if self.bound_dims.iter().any(|(w, _)| *w == v) {
            return true;
        }
        if let Some(m) = self.module
            && (self.elab.module(m).typarams.contains(&v) || self.extra.contains(&v))
        {
            return true;
        }
        false
    }

    /// A body: `let`s become assignments, the last expression a `return`.
    fn body(&mut self, e: &Expr) {
        let mut cur = e;
        loop {
            match cur {
                Expr::Let { pat, init, body, .. } => {
                    let target = self.pat(pat);
                    let ty = self.typed.ty_of.get(&init.span()).map(|t| format!("  # {}", t.display(&self.elab.names()))).unwrap_or_default();
                    // A stacked `apply` is a loop, printed as statements into the
                    // bound name (checked before `expr`, which would hoist it).
                    if let Some(stmts) = self.stack_loop(init, &target) {
                        for s in stmts {
                            self.line(&s);
                        }
                    } else {
                        let v = self.expr(init);
                        self.line(&format!("{target} = {v}{ty}"));
                    }
                    if self.opts.shapes_check
                        && let Some(t) = self.typed.ty_of.get(&init.span())
                        && let Some(shape) = t.shape()
                        && shape.prefix.is_none()
                        && let Pat::Ident(_) = pat
                    {
                        let sh = self.py_shape(shape, false);
                        self.line(&format!("assert {target}.shape == ({sh},), str(tuple({target}.shape))"));
                    }
                    cur = body;
                }
                other => {
                    let v = self.expr(other);
                    self.line(&format!("return {v}"));
                    return;
                }
            }
        }
    }

    /// Whether `fid` is `uses Rand`, and so takes the `training` keyword.
    fn has_rand(&self, fid: FnId) -> bool {
        self.elab.function(fid).effects.iter().any(|e| e == "Rand")
    }

    /// The keywords a call to `callee` passes on: the caller's own, when both
    /// are `uses Rand` (the effect discipline makes the caller so).
    fn rand_kwargs(&self, callee: FnId) -> Option<String> {
        (self.has_rand(callee) && self.fn_id.is_some_and(|f| self.has_rand(f))).then(|| "training=training".to_string())
    }

    /// `blocks.apply(h0, mask)` through `stack{L}(Block)`: a loop.
    fn stack_loop(&mut self, init: &Expr, target: &str) -> Option<Vec<String>> {
        let Expr::Call { callee, args, span } = init else { return None };
        let Some(Callee::Fn { id, module: Some(ModRef::Stack { n, .. }), .. }) = self.typed.callees.get(span) else { return None };
        let (id, n) = (*id, n.clone());
        let Expr::Var { path } = &**callee else { return None };
        let member = path.segs[0].name.clone();
        let mut vals: Vec<String> = Vec::new();
        for a in args {
            if let Arg::Pos(e) = a {
                vals.push(self.expr(e));
            }
        }
        let first = vals.first()?.clone();
        let rest = vals[1..].join(", ");
        let mut comma = if rest.is_empty() { String::new() } else { format!(", {rest}") };
        if let Some(kw) = self.rand_kwargs(id) {
            comma.push_str(&format!(", {kw}"));
        }
        // A tuple accumulator (`let (hL, _) = blocks.apply((h0, kb), mask)`,
        // the key threaded through the fold, D37) is bound by a tuple pattern
        // and passed back as one argument.
        let acc = if target.contains(',') { format!("({target})") } else { target.to_string() };
        match self.opts.stack {
            StackMode::Loop => Some(vec![format!("{target} = {first}"), format!("for block in self.{member}:  # stack{{{}}}", self.dim(&n)), format!("    {target} = block({acc}{comma})")]),
            StackMode::Unroll => {
                let count = n.as_nat()? as usize;
                let mut out = vec![format!("{target} = {first}")];
                for i in 0..count {
                    out.push(format!("{target} = self.{member}[{i}]({acc}{comma})"));
                }
                Some(out)
            }
        }
    }

    fn pat(&mut self, p: &Pat) -> String {
        match p {
            Pat::Ident(i) => i.name.clone(),
            Pat::Tuple { elems, .. } => elems.iter().map(|e| self.pat(e)).collect::<Vec<_>>().join(", "),
        }
    }

    // ----- shapes and dimensions ---------------------------------------

    /// A shape as Python arguments: `In, Out`; `self.` prefix for module type
    /// parameters when `in_init`.
    fn py_shape(&mut self, s: &Shape, in_init: bool) -> String {
        let _ = in_init;
        s.axes.iter().map(|a| self.dim(&a.len)).collect::<Vec<_>>().join(", ")
    }

    /// A dimension written in the source (a named axis's length, a slice's
    /// bound) as Python: as an expression, but a quotient, which is exact
    /// in the fragment, as the integer quotient (`HD // 2`; `HD / 2` would
    /// be a float).
    fn dim_src(&mut self, e: &Expr) -> String {
        fn has_div(e: &Expr) -> bool {
            match e {
                Expr::Binary { op: BinOp::Div, .. } => true,
                Expr::Binary { lhs, rhs, .. } => has_div(lhs) || has_div(rhs),
                _ => false,
            }
        }
        match e {
            Expr::Binary { op, lhs, rhs, .. } if has_div(e) && matches!(op, BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div) => {
                let o = match op {
                    BinOp::Add => "+",
                    BinOp::Sub => "-",
                    BinOp::Mul => "*",
                    _ => "//",
                };
                format!("({} {o} {})", self.dim_src(lhs), self.dim_src(rhs))
            }
            other => self.expr(other),
        }
    }

    /// A dimension expression as Python.
    fn dim(&mut self, e: &DimExpr) -> String {
        if let Some(n) = e.as_nat() {
            return n.to_string();
        }
        let elab = self.elab;
        let module = self.module;
        let bound = self.bound_dims.clone();
        let extra = self.extra.clone();
        let name = |v: DimVar| -> String {
            let n = elab.dim_name(v);
            if let Some((_, py)) = bound.iter().find(|(w, _)| *w == v) {
                return py.clone();
            }
            if let Some(m) = module
                && (elab.module(m).typarams.contains(&v) || extra.contains(&v))
            {
                return format!("self.{n}");
            }
            n
        };
        // Integer coefficients print as `4*D`; rational ones as `D // 12` (exact by construction).
        let mut parts: Vec<String> = Vec::new();
        for (v, c) in &e.coeffs {
            let n = name(*v);
            let term = if c.is_integer() {
                let k = c.numer();
                if *c == rat(1) { n } else { format!("{k}*{n}") }
            } else if *c.numer() == 1.into() {
                format!("{n} // {}", c.denom())
            } else {
                format!("{}*{n} // {}", c.numer(), c.denom())
            };
            parts.push(term);
        }
        if !e.constant.is_integer() {
            parts.push(format!("({})", e.constant));
        } else if e.constant != rat(0) {
            parts.push(e.constant.numer().to_string());
        }
        parts.join(" + ")
    }

    // ----- expressions ---------------------------------------------------

    /// Expressions in dimension/hyperparameter position (`--const` values are
    /// already substituted by the elaboration: print names, not values).
    fn raw_expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Lit { lit, .. } => lit_py(lit),
            Expr::Var { path } => path.dotted(),
            Expr::Binary { op, lhs, rhs, .. } => {
                let (l, r) = (self.raw_expr(lhs), self.raw_expr(rhs));
                match op {
                    BinOp::Pipe => format!("{l} |> {r}"),
                    BinOp::Alt => format!("{l} | {r}"),
                    BinOp::Tensor => format!("{l} ⊗ {r}"),
                    BinOp::Compose => format!("{l} ∘ {r}"),
                    BinOp::Pow => format!("{l} ** {r}"),
                    BinOp::Dot => format!("{l} @ {r}"),
                    BinOp::Div => format!("{l} // {r}"),
                    BinOp::Rem => format!("{l} % {r}"),
                    other => format!("{l} {} {r}", other.text()),
                }
            }
            Expr::Call { callee, args, .. } => {
                let c = self.raw_expr(callee);
                let a: Vec<String> = args.iter().map(|a| match a {
                    Arg::Pos(e) => self.raw_expr(e),
                    Arg::Named { name, value } => format!("{}={}", name.name, self.raw_expr(value)),
                    Arg::Axis(id) => format!("axis {}", id.name),
                    Arg::NamedAxis { name, value } => format!("{}: {}", name.name, self.raw_expr(value)),
                }).collect();
                format!("{c}({})", a.join(", "))
            }
            Expr::Tuple { elems, .. } => format!("({})", elems.iter().map(|e| self.raw_expr(e)).collect::<Vec<_>>().join(", ")),
            Expr::Unary { expr, .. } => format!("-{}", self.raw_expr(expr)),
            other => {
                let _ = other;
                "…".into()
            }
        }
    }

    fn ty_of(&self, e: &Expr) -> Option<&Ty> {
        self.typed.ty_of.get(&e.span())
    }

    fn is_tensor(&self, e: &Expr) -> bool {
        self.ty_of(e).is_some_and(|t| t.is_tensor())
    }

    /// Is the Python value a `torch.Tensor`? A hyperparameter injected into
    /// `ℝ[]` (`(HD : ℝ)`, `real(eps)`) stays a Python number.
    fn is_py_tensor(&self, e: &Expr) -> bool {
        match e {
            Expr::Ascribe { expr, .. } => self.is_py_tensor(expr),
            Expr::Call { callee, args, .. } if matches!(&**callee, Expr::Var { path } if path.is_single("real")) => {
                args.iter().any(|a| matches!(a, Arg::Pos(e) if matches!(self.ty_of(e), Some(Ty::Idx { .. }))))
            }
            _ => self.is_tensor(e),
        }
    }

    /// Print `e` for a context of precedence `min`: parenthesized when its own
    /// precedence is lower. Precedences: atoms/calls 90, unary 80, `**` 75,
    /// `* / @` 60, `+ -` 50, anything else 10.
    fn expr_at(&mut self, e: &Expr, min: u8) -> String {
        let s = self.expr(e);
        let p = match e {
            Expr::Binary { op: BinOp::Pow, .. } => 75,
            Expr::Binary { op: BinOp::Dot | BinOp::Mul | BinOp::Div, .. } => 60,
            Expr::Binary { op: BinOp::Add | BinOp::Sub, .. } => 50,
            Expr::Binary { .. } => 10,
            Expr::Unary { .. } => 80,
            Expr::Lambda { .. } => 5,
            Expr::Ascribe { expr, .. } if self.is_tensor(expr) => return self.expr_at(expr, min),
            _ => 90,
        };
        if p < min { format!("({s})") } else { s }
    }

    pub(crate) fn expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Lit { lit, .. } => lit_py(lit),
            Expr::Var { path } => {
                // Module parameters and sub-modules are attributes of self.
                if let Some(m) = self.module
                    && path.segs.len() == 1
                {
                    let def = self.elab.module(m);
                    let n = &path.segs[0].name;
                    if def.params.iter().any(|p| &p.name == n) || def.uses.iter().any(|u| &u.name == n) {
                        return format!("self.{n}");
                    }
                }
                // A module value (`m.MiniGPT`) used as a value: an instance.
                if let Some(Ty::Module(r)) = self.ty_of(e).cloned() {
                    if self.module_params.iter().any(|(n, _)| path.is_single(n)) {
                        return path.dotted();
                    }
                    return self.mod_ctor(&r);
                }
                // Dimensions bound from shapes, or constructor dimensions of the module.
                if path.segs.len() == 1 {
                    if let Some((_, py)) = self.bound_dims.iter().find(|(v, _)| self.elab.dim_name(*v) == path.segs[0].name) {
                        return py.clone();
                    }
                    if let Some(m) = self.module {
                        let n = &path.segs[0].name;
                        if self.elab.module(m).typarams.iter().chain(&self.extra).any(|v| self.elab.dim_name(*v) == *n) {
                            return format!("self.{n}");
                        }
                    }
                }
                path.segs.last().map(|s| s.name.clone()).unwrap_or_default()
            }
            Expr::Let { .. } => {
                self.error(e.span(), "`let` inside an expression cannot be exported to Python");
                "None".into()
            }
            Expr::Lambda { pat, body, .. } => {
                let p = self.pat(pat);
                let b = self.expr(body);
                format!("lambda {p}: {b}")
            }
            Expr::Call { callee, args, span } => self.call(callee, args, *span),
            Expr::Index { base, sels, .. } => {
                let b = self.expr_at(base, 90);
                let Some(Ty::Real(s) | Ty::Idx { shape: s, .. }) = self.ty_of(base).cloned() else { return b };
                let mut idx: Vec<String> = vec![":".into(); s.axes.len()];
                for sel in sels {
                    match sel {
                        IndexSel::Named { axis, value } => {
                            if let Some(k) = s.axes.iter().position(|a| a.name.as_deref() == Some(&axis.name)) {
                                idx[k] = self.expr(value);
                            }
                        }
                        IndexSel::Pos(value) => {
                            if let Some(k) = idx.iter().position(|x| x == ":") {
                                idx[k] = self.expr(value);
                            }
                        }
                        // A slice keeps its axis, as Python's does.
                        IndexSel::Slice { axis, lo, hi } => {
                            let k = match axis {
                                Some(axis) => s.axes.iter().position(|a| a.name.as_deref() == Some(&axis.name)),
                                None => idx.iter().position(|x| x == ":"),
                            };
                            if let Some(k) = k {
                                idx[k] = format!("{}:{}", self.dim_src(lo), self.dim_src(hi));
                            }
                        }
                    }
                }
                // Under an open prefix the selectors are of the written
                // axes, the last ones: `...` first, and every one kept.
                if s.prefix.is_some() {
                    return format!("{b}[..., {}]", idx.join(", "));
                }
                while idx.last().is_some_and(|x| x == ":") {
                    idx.pop();
                }
                format!("{b}[{}]", idx.join(", "))
            }
            Expr::Ein { body, span, .. } => {
                let Some(info) = self.typed.eins.get(span).cloned() else { return "None".into() };
                let mut ops = Vec::new();
                collect_product(body, &mut ops);
                // One letter per axis name.
                let mut letters: Vec<(String, char)> = Vec::new();
                let letter = |n: &str, letters: &mut Vec<(String, char)>| -> char {
                    if let Some((_, c)) = letters.iter().find(|(m, _)| m == n) {
                        return *c;
                    }
                    let c = (b'a' + letters.len() as u8) as char;
                    letters.push((n.to_string(), c));
                    c
                };
                let mut specs: Vec<String> = Vec::new();
                for (_, axes) in &info.operands {
                    specs.push(axes.iter().map(|a| letter(a.name.as_deref().unwrap_or("?"), &mut letters)).collect());
                }
                let out: String = info.output.iter().map(|a| letter(a.name.as_deref().unwrap_or("?"), &mut letters)).collect();
                let args: Vec<String> = ops.iter().map(|o| self.expr(o)).collect();
                format!("torch.einsum(\"{}->{out}\", {})", specs.join(","), args.join(", "))
            }
            Expr::Binary { op, lhs, rhs, .. } => {
                let (p, py_op) = match op {
                    BinOp::Pow => (75, "**"),
                    BinOp::Dot => (60, "@"),
                    BinOp::Mul => (60, "*"),
                    BinOp::Div => (60, "/"),
                    BinOp::Add => (50, "+"),
                    BinOp::Sub => (50, "-"),
                    other => (10, other.text()),
                };
                // Left-associative except `**`: the right operand needs strictly higher precedence.
                let mut l = self.expr_at(lhs, if *op == BinOp::Pow { p + 1 } else { p });
                let mut r = self.expr_at(rhs, if *op == BinOp::Pow { p } else { p + 1 });
                if matches!(op, BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div)
                    && let (Some(Ty::Real(ls)), Some(Ty::Real(rs))) = (self.ty_of(lhs).cloned(), self.ty_of(rhs).cloned())
                {
                    let (lr, rr) = (ls.axes.len(), rs.axes.len());
                    if lr < rr || (lr == rr && ls.prefix.is_none() && rs.prefix.is_some()) {
                        l = self.broadcast_fix(&ls, &rs, l);
                    } else if rr < lr || (lr == rr && rs.prefix.is_none() && ls.prefix.is_some()) {
                        r = self.broadcast_fix(&rs, &ls, r);
                    }
                }
                format!("{l} {py_op} {r}")
            }
            Expr::Unary { op: UnOp::Neg, expr, .. } => format!("-{}", self.expr_at(expr, 80)),
            Expr::Ascribe { expr, .. } => {
                // `(HD : ℝ)`: a hyperparameter used as a real; Python numbers already are.
                let inner = self.expr(expr);
                if self.is_tensor(expr) { inner } else { format!("float({inner})") }
            }
            Expr::Tuple { elems, .. } => format!("({})", elems.iter().map(|e| self.expr(e)).collect::<Vec<_>>().join(", ")),
            Expr::Field { .. } | Expr::Inst { .. } => {
                self.error(e.span(), "not exportable");
                "None".into()
            }
        }
    }

    fn call(&mut self, callee: &Expr, args: &[Arg], span: Span) -> String {
        let resolved = self.typed.callees.get(&span).cloned();
        let pos: Vec<&Expr> = args.iter().filter_map(|a| match a {
            Arg::Pos(e) => Some(e),
            _ => None,
        }).collect();
        match resolved {
            Some(Callee::Fn { module: Some(ModRef::Stack { .. }), .. }) => {
                // A stacked `apply` nested in an expression: the loop is printed
                // as statements before the current one, into a temporary.
                let target = format!("_stack{}", self.temps);
                self.temps += 1;
                let e = Expr::Call { callee: Box::new(callee.clone()), args: args.to_vec(), span };
                match self.stack_loop(&e, &target) {
                    Some(stmts) => {
                        for s in stmts {
                            self.line(&s);
                        }
                        target
                    }
                    None => "None".into(),
                }
            }
            Some(Callee::Fn { id, module, explicit_theta }) => {
                let Expr::Var { path } = callee else { return "None".into() };
                let fname = path.segs.last().unwrap().name.clone();
                let py_name = if fname == "apply" { None } else { Some(fname.clone()) };
                let keep_modules = module.is_none();
                let mut vals: Vec<String> = Vec::new();
                for a in args {
                    match a {
                        Arg::Pos(e) if matches!(self.ty_of(e), Some(Ty::Module(_))) && !keep_modules => {}
                        Arg::Pos(e) => vals.push(self.expr(e)),
                        Arg::Named { name, value } => vals.push(format!("{}={}", name.name, self.expr(value))),
                        _ => {}
                    }
                }
                let kw = self.rand_kwargs(id);
                match (module, explicit_theta) {
                    (Some(_), false) => {
                        // `l1.apply(x)` inside a module: a sub-module call.
                        let member = path.segs[0].name.clone();
                        vals.extend(kw);
                        match py_name {
                            None => format!("self.{member}({})", vals.join(", ")),
                            Some(n) => format!("self.{member}.{n}({})", vals.join(", ")),
                        }
                    }
                    (Some(r), true) => {
                        // `net.apply(θ, x)` / `m.MiniGPT.apply(θ, x)`: functional call with the parameter tree.
                        let theta = vals.remove(0);
                        let modexpr = if path.segs.len() == 2 && self.module_params.iter().any(|(n, _)| path.segs[0].name == *n) { path.segs[0].name.clone() } else { self.mod_ctor(&r) };
                        let target = match py_name {
                            None => modexpr,
                            Some(n) => format!("{modexpr}.{n}"),
                        };
                        let kwargs = if kw.is_some() { ", {\"training\": training}" } else { "" };
                        format!("torch.func.functional_call({target}, {theta}, ({},){kwargs})", vals.join(", "))
                    }
                    (None, _) => {
                        for v in self.dims_passed(id) {
                            let n = self.elab.dim_name(v);
                            vals.push(format!("{n}={n}"));
                        }
                        vals.extend(kw);
                        format!("{fname}({})", vals.join(", "))
                    }
                }
            }
            Some(Callee::Builtin(name)) => self.builtin(&name, args, &pos, span),
            Some(Callee::Value) | None => {
                let c = self.expr(callee);
                let a: Vec<String> = pos.iter().map(|e| self.expr(e)).collect();
                format!("{c}({})", a.join(", "))
            }
        }
    }

    /// The PyTorch `dim` of an `axis a` argument: the checker's position among
    /// the explicit axes, counted from the end when the tensor's type has an
    /// open prefix `...` (its leading axes are unknown in number).
    fn axis_pos(&self, args: &[Arg], pos: &[&Expr]) -> Option<i64> {
        let k = args.iter().find_map(|a| match a {
            Arg::Axis(id) => self.typed.axis_pos.get(&id.span).copied(),
            _ => None,
        })?;
        let shape = pos.first().and_then(|e| self.ty_of(e)).and_then(|t| t.shape().cloned());
        match shape {
            Some(s) if s.prefix.is_some() => Some(k as i64 - s.axes.len() as i64),
            _ => Some(k as i64),
        }
    }

    /// The two operands `i` and `j` of a comparison, each aligned with the
    /// other as an arithmetic operator's are and bound to a temporary unless
    /// it is a name or a number, since a selection writes each twice.
    fn compared(&mut self, pos: &[&Expr], i: usize, j: usize) -> (String, String) {
        let (Some(ea), Some(eb)) = (pos.get(i), pos.get(j)) else { return ("None".into(), "None".into()) };
        let (mut a, mut b) = (self.expr_at(ea, 90), self.expr_at(eb, 90));
        if let (Some(Ty::Real(ls)), Some(Ty::Real(rs))) = (self.ty_of(ea).cloned(), self.ty_of(eb).cloned()) {
            let (lr, rr) = (ls.axes.len(), rs.axes.len());
            if lr < rr || (lr == rr && ls.prefix.is_none() && rs.prefix.is_some()) {
                a = self.broadcast_fix(&ls, &rs, a);
            } else if rr < lr || (lr == rr && rs.prefix.is_none() && ls.prefix.is_some()) {
                b = self.broadcast_fix(&rs, &ls, b);
            }
        }
        (self.named_temp(a), self.named_temp(b))
    }

    /// `text` itself when it is a name or a number, else a temporary that
    /// holds it, written on a line before the current one.
    fn named_temp(&mut self, text: String) -> String {
        if text.chars().all(|c| c.is_alphanumeric() || c == '_' || c == '.') {
            return text;
        }
        let t = format!("_cmp{}", self.temps);
        self.temps += 1;
        self.line(&format!("{t} = {text}"));
        t
    }

    /// Make `short` broadcast against `long` as Presk does (leading prefix
    /// alignment, or alignment by name) where PyTorch would align from the
    /// trailing axis: insert `unsqueeze`s for the axes it lacks.
    fn broadcast_fix(&self, short: &Shape, long: &Shape, text: String) -> String {
        if short.prefix.is_some() && long.prefix.is_some() {
            // Same prefix: the tails align at the front; append missing axes.
            let missing = long.axes.len().saturating_sub(short.axes.len());
            let mut t = text;
            for _ in 0..missing {
                t = format!("{t}.unsqueeze(-1)");
            }
            return t;
        }
        if short.prefix.is_none() && long.prefix.is_some() && short.axes.len() <= long.axes.len() {
            // A closed operand against the written axes of an open one: by
            // name when the trailing axes do not face their names, its
            // missing axes inserted from the right (`unsqueeze(-k)`).
            let off = long.axes.len() - short.axes.len();
            let trailing_ok = short.axes.iter().enumerate().all(|(i, a)| {
                let l = &long.axes[off + i];
                a.name.is_none() || l.name.is_none() || a.name == l.name
            });
            if trailing_ok || short.axes.iter().any(|a| a.name.is_none()) {
                return text;
            }
            let n = long.axes.len() as i64;
            let mut t = text;
            for (j, l) in long.axes.iter().enumerate().rev() {
                if !short.axes.iter().any(|a| a.name == l.name) {
                    t = format!("{t}.unsqueeze({})", j as i64 - n);
                }
            }
            return t;
        }
        if short.prefix.is_none() && long.prefix.is_none() && short.axes.len() < long.axes.len() {
            // Trailing alignment is what PyTorch does; only fix a by-name alignment.
            let off = long.axes.len() - short.axes.len();
            let trailing_ok = short.axes.iter().enumerate().all(|(i, a)| {
                let l = &long.axes[off + i];
                a.name.is_none() || l.name.is_none() || a.name == l.name
            });
            if trailing_ok || short.axes.iter().any(|a| a.name.is_none()) {
                return text;
            }
            let mut t = text;
            for (i, l) in long.axes.iter().enumerate() {
                if !short.axes.iter().any(|a| a.name == l.name) {
                    t = format!("{t}.unsqueeze({i})");
                }
            }
            return t;
        }
        text
    }

    fn builtin(&mut self, name: &str, args: &[Arg], pos: &[&Expr], span: Span) -> String {
        let x = |p: &mut Self, i: usize| -> String { pos.get(i).map(|e| p.expr_at(e, 90)).unwrap_or_else(|| "None".into()) };
        match name {
            "gelu" => format!("F.gelu({})", x(self, 0)),
            "relu" => format!("F.relu({})", x(self, 0)),
            "sigmoid" => format!("torch.sigmoid({})", x(self, 0)),
            "exp" | "log" | "tanh" | "sqrt" | "abs" | "sin" | "cos" => {
                let a = x(self, 0);
                if pos.first().is_some_and(|e| self.is_py_tensor(e)) { format!("torch.{name}({a})") } else { format!("math.{name}({a})") }
            }
            "mean" | "sum" => {
                let a = x(self, 0);
                match self.axis_pos(args, pos) {
                    Some(k) => format!("{a}.{name}(dim={k})"),
                    None => format!("{a}.{name}()"),
                }
            }
            "softmax" => {
                let a = x(self, 0);
                let k = self.axis_pos(args, pos).unwrap_or(-1);
                // `where = m` (plan 0.10.0 step 7b): the refused positions
                // filled with `-inf`, whose exponential is 0, the mask
                // aligned with the scores as Presk aligns it.
                let mask = args.iter().find_map(|a| match a {
                    Arg::Named { name, value } if name.name == "where" => Some(value),
                    _ => None,
                });
                match mask {
                    None => format!("torch.softmax({a}, dim={k})"),
                    Some(m) => {
                        let mt = self.expr_at(m, 90);
                        let mt = match (self.ty_of(m).and_then(|t| t.shape().cloned()), pos.first().and_then(|e| self.ty_of(e)).and_then(|t| t.shape().cloned())) {
                            (Some(ms), Some(xs)) => self.broadcast_fix(&ms, &xs, mt),
                            _ => mt,
                        };
                        format!("torch.softmax({a}.masked_fill(~{mt}, float(\"-inf\")), dim={k})")
                    }
                }
            }
            "real" => {
                let a = x(self, 0);
                if pos.first().is_some_and(|e| matches!(self.ty_of(e), Some(Ty::Idx { .. }))) { format!("{a}.to(torch.get_default_dtype())") } else { a }
            }
            "merge" => {
                let k = self.axis_pos(args, pos).unwrap_or(-2);
                format!("{}.flatten({k}, {})", x(self, 0), k + 1)
            }
            "split" => {
                // The inverse of `merge`, and of its export: one axis read as
                // two, row-major, so the first new axis is the outer one.
                let k = self.axis_pos(args, pos).unwrap_or(-1);
                let lens: Vec<String> = args
                    .iter()
                    .filter_map(|a| match a {
                        Arg::NamedAxis { value, .. } => Some(self.dim_src(value)),
                        _ => None,
                    })
                    .collect();
                let (l1, l2) = (lens.first().cloned().unwrap_or_else(|| "None".into()), lens.get(1).cloned().unwrap_or_else(|| "None".into()));
                format!("{}.unflatten({k}, ({l1}, {l2}))", x(self, 0))
            }
            "split_key" => {
                // The exported program never draws from a key: `dropout` at
                // its expectation ignores it, and under the `training` switch
                // PyTorch's own generator draws the mask, so both halves are
                // the same value.
                let k = x(self, 0);
                format!("({k}, {k})")
            }
            "dropout" => {
                // The mask is a function of a Presk key, which PyTorch's
                // generator cannot reproduce. With the switch off the export
                // is the random function's expectation — the identity of
                // inverted dropout, and what an inference deployment wants
                // (question 33); `train.py` turns it on, and PyTorch draws
                // masks of its own (D54).
                let switch = if self.fn_id.is_some_and(|f| self.has_rand(f)) { "training" } else { "False" };
                format!("F.dropout({}, {}, training={switch})", x(self, 2), x(self, 0))
            }
            "embed" => format!("{}[{}]", x(self, 0), x(self, 1)),
            "one_hot" => {
                let bound = pos.first().and_then(|e| match self.ty_of(e) {
                    Some(Ty::Idx { bound, .. }) => Some(bound.clone()),
                    _ => None,
                });
                let v = match bound {
                    Some(b) => self.dim(&b),
                    None => "None".to_string(),
                };
                format!("F.one_hot({}, {v}).to(torch.get_default_dtype())", x(self, 0))
            }
            "cross_entropy" => {
                let (l, y) = (x(self, 0), x(self, 1));
                format!("F.cross_entropy({l}.flatten(0, -2), {y}.flatten(), reduction=\"none\").view({y}.shape)")
            }
            "argmax" => format!("{}.argmax(dim=-1)", x(self, 0)),
            // `sample(key, logits)`: drawn from PyTorch's generator, not from
            // the key (plan 0.10.0 step 7b).
            "sample" => format!("torch.multinomial(torch.softmax({}, dim=-1), 1).squeeze(-1)", x(self, 1)),
            "split_heads" => format!("_split_heads({}, H, HD)", x(self, 0)),
            "merge_heads" => format!("_merge_heads({}, H, HD)", x(self, 0)),
            "positions" | "causal_mask" => {
                let n = args.iter().find_map(|a| match a {
                    Arg::NamedAxis { value, .. } => Some(self.dim_src(value)),
                    _ => None,
                }).unwrap_or_else(|| "None".into());
                // A mask: true where j ≤ i (plan 0.10.0 step 7b).
                if name == "positions" { format!("torch.arange({n})") } else { format!("torch.ones(({n}, {n}), dtype=torch.bool).tril()") }
            }
            "grad" => format!("torch.func.grad({})", x(self, 0)),
            "matmul" => format!("{} @ {}", x(self, 0), x(self, 1)),
            // `max`, `min` and `clamp` as selections, so that a tie takes the
            // second operand and its gradient, as the reference assigns
            // (`torch.maximum` would split a tie's gradient in two).
            "max" | "min" => {
                let (a, b) = self.compared(pos, 0, 1);
                let cmp = if name == "max" { ">" } else { "<" };
                format!("torch.where({a} {cmp} {b}, {a}, {b})")
            }
            "clamp" => {
                let (a, lo) = self.compared(pos, 0, 1);
                let m = format!("_clamp{}", self.temps);
                self.temps += 1;
                self.line(&format!("{m} = torch.where({a} > {lo}, {a}, {lo})"));
                let hi = pos.get(2).map(|e| self.expr_at(e, 90)).unwrap_or_else(|| "None".into());
                let hi = self.named_temp(hi);
                format!("torch.where({m} < {hi}, {m}, {hi})")
            }
            "concat" => {
                let k = self.axis_pos(args, pos).unwrap_or(-1);
                format!("torch.cat(({}, {}), dim={k})", x(self, 0), x(self, 1))
            }
            other => {
                self.error(span, format!("builtin `{other}` has no PyTorch export"));
                "None".into()
            }
        }
    }
}

fn lit_py(l: &Lit) -> String {
    match l {
        Lit::Nat(n) => n.clone(),
        Lit::Float(f) => f.clone(),
        Lit::Str(s) => format!("{s:?}"),
        Lit::Quantity { num, unit } => format!("\"{num}{unit}\""),
    }
}

/// `X + c`, one dimension of coefficient 1 and an integer constant: the
/// length of an axis from which `X` is the shape less `c` (a window's
/// `seq: T + 1`).
fn affine_var(e: &DimExpr) -> Option<(DimVar, i64)> {
    if e.coeffs.len() == 1 {
        let (v, c) = e.coeffs.iter().next().unwrap();
        if *c == rat(1) && e.constant.is_integer() {
            return e.constant.to_integer().try_into().ok().map(|k: i64| (*v, k));
        }
    }
    None
}

/// `shape` less the constant `k` of an axis's length.
fn less(shape: String, k: i64) -> String {
    match k {
        0 => shape,
        k if k > 0 => format!("{shape} - {k}"),
        k => format!("{shape} + {}", -k),
    }
}

/// Every name an expression reads, every call in it, every dimension a
/// named axis or a slice writes: `f` on each name, `g` on each call's span.
fn walk_names(e: &Expr, f: &mut dyn FnMut(&str), g: &mut dyn FnMut(Span)) {
    let arg = |a: &Arg, f: &mut dyn FnMut(&str), g: &mut dyn FnMut(Span)| match a {
        Arg::Pos(x) | Arg::Named { value: x, .. } | Arg::NamedAxis { value: x, .. } => walk_names(x, f, g),
        Arg::Axis(_) => {}
    };
    match e {
        Expr::Lit { .. } => {}
        Expr::Var { path } => {
            if path.segs.len() == 1 {
                f(&path.segs[0].name);
            }
        }
        Expr::Let { init, body, .. } => {
            walk_names(init, f, g);
            walk_names(body, f, g);
        }
        Expr::Lambda { body, .. } => walk_names(body, f, g),
        Expr::Call { callee, args, span } => {
            g(*span);
            walk_names(callee, f, g);
            for a in args {
                arg(a, f, g);
            }
        }
        Expr::Field { base, .. } => walk_names(base, f, g),
        Expr::Index { base, sels, .. } => {
            walk_names(base, f, g);
            for sel in sels {
                match sel {
                    IndexSel::Pos(x) | IndexSel::Named { value: x, .. } => walk_names(x, f, g),
                    IndexSel::Slice { lo, hi, .. } => {
                        walk_names(lo, f, g);
                        walk_names(hi, f, g);
                    }
                }
            }
        }
        Expr::Inst { base, args, .. } => {
            walk_names(base, f, g);
            for a in args {
                walk_names(a, f, g);
            }
        }
        Expr::Ein { body, .. } => walk_names(body, f, g),
        Expr::Binary { lhs, rhs, .. } => {
            walk_names(lhs, f, g);
            walk_names(rhs, f, g);
        }
        Expr::Unary { expr, .. } | Expr::Ascribe { expr, .. } => walk_names(expr, f, g),
        Expr::Tuple { elems, .. } => {
            for x in elems {
                walk_names(x, f, g);
            }
        }
    }
}

fn collect_product<'e>(e: &'e Expr, out: &mut Vec<&'e Expr>) {
    match e {
        Expr::Binary { op: BinOp::Mul, lhs, rhs, .. } => {
            collect_product(lhs, out);
            collect_product(rhs, out);
        }
        e => out.push(e),
    }
}
