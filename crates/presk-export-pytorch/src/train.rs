//! `presk export --train`: the `training run` of the source as a PyTorch
//! loop (`train.py`) over a generated reader of `.psk.d` files (`pskd.py`).
//!
//! The loop uses the exported objective as is (`loss(θ, batch)` with `θ` a
//! dict of the model's parameters, differentiated by autograd), the block's
//! hyperparameters in `torch.optim.AdamW`, the schedule as a multiplier set
//! before every step, `clip_grad_norm_` for `grad_clip`, and PyTorch's own
//! shuffling. The interpreter's permutation is not reproduced: the K-step
//! conformance test replays the interpreter's batches instead. An objective
//! that takes a per-step key gets `None` for it and the `training` switch
//! on, so that `dropout` drops here as it does under `presk train`, with
//! masks PyTorch draws (D54).

use crate::Generated;

/// The schedule of an `optimizer` block.
#[derive(Clone, Debug, PartialEq)]
pub enum Schedule {
    Constant,
    Linear { warmup: u64 },
    Cosine { warmup: u64 },
}

/// What `train.py` needs from the source and the run.
#[derive(Clone, Debug)]
pub struct TrainSpec {
    /// Source file, for the header comment.
    pub source: String,
    /// Python module (stem) defining the model class, and the class constructor call.
    pub model_stem: String,
    pub ctor: String,
    /// Python module (stem) defining the objective, and its name.
    pub objective_stem: String,
    pub objective: String,
    pub lr: String,
    pub betas: (String, String),
    pub eps: String,
    pub weight_decay: String,
    pub grad_clip: Option<String>,
    pub schedule: Schedule,
    pub batch: usize,
    pub shuffle: Option<u64>,
    pub epochs: u64,
    pub checkpoint_every: Option<u64>,
    /// The `checkpoint … to "dir"` clause, relative to the output directory.
    pub checkpoint_dir: Option<String>,
    /// The objective takes a per-step key between `θ` and the batch.
    pub key: bool,
    /// The objective `uses Rand`, so it has the `training` switch.
    pub rand: bool,
    /// Dimensions fixed by the run (`B = 32, T = 8`), for the header.
    pub dims: Vec<(String, u64)>,
    /// The `parallel` and `precision` clauses, reproduced as comments.
    pub comments: Vec<String>,
}

/// The learning-rate multiplier at step `t` (from 1) of `total`, as a Python
/// expression over `t` and `total` (floats).
pub fn schedule_py(s: &Schedule) -> String {
    match s {
        Schedule::Constant => "1.0".into(),
        Schedule::Linear { warmup } => {
            let w = *warmup as f64;
            let warm = if *warmup == 0 { "1.0".to_string() } else { format!("min(1.0, t / {w})") };
            format!("{warm} * (1.0 - min(1.0, max(0.0, (t - {w}) / max(total - {w}, 1.0))))")
        }
        Schedule::Cosine { warmup } => {
            let w = *warmup as f64;
            let warm = if *warmup == 0 { "1.0".to_string() } else { format!("min(1.0, t / {w})") };
            format!("{warm} * 0.5 * (1.0 + math.cos(math.pi * min(1.0, max(0.0, (t - {w}) / max(total - {w}, 1.0)))))")
        }
    }
}

fn describe(s: &Schedule) -> String {
    match s {
        Schedule::Constant => "constant()".into(),
        Schedule::Linear { warmup } => format!("linear(warmup = {warmup})"),
        Schedule::Cosine { warmup } => format!("cosine(warmup = {warmup})"),
    }
}

fn py_opt<T: std::fmt::Display>(v: &Option<T>) -> String {
    match v {
        Some(x) => x.to_string(),
        None => "None".into(),
    }
}

/// `pskd.py` and `train.py`.
pub fn train_files(spec: &TrainSpec) -> Vec<Generated> {
    vec![Generated { name: "pskd.py".into(), content: PSKD_PY.to_string() }, Generated { name: "train.py".into(), content: train_py(spec) }]
}

/// The objective's call on one batch: `None` for a per-step key (the export
/// threads keys as values and never draws from them), the `training` switch
/// on when the objective has it.
pub fn objective_call(objective: &str, key: bool, rand: bool) -> String {
    let mut args = vec!["theta"];
    if key {
        args.push("None");
    }
    args.push("batch");
    if rand {
        args.push("training=True");
    }
    format!("{objective}({})", args.join(", "))
}

