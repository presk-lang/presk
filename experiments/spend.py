#!/usr/bin/env python3
"""Three ways to spend the budget, judged out of sample (plan 0.16.0 step 4,
D161): experiments/spend.sh's two commands.

  spend.py unique OUT     every distinct realization of OUT/solve/*.json, as
                          OUT/margins/realizations/<name>.json (off_sample.py's)
  spend.py report OUT --sizes "4 16" --budgets "4.67e-4 1e-6" --forms "…" --margin 2.5

The report judges every realization on the same windows at each size: the
envelope's N (in sample) against the windows from 2N on (out of sample),
which no form saw, `--narrow heldout` having measured the N after the
envelope's. Then the plan's rule (§1, decision 5): a form becomes a default
only if, in every cell (both sizes, both budgets), its gap out of sample is
inside the budget with a margin of at least 1.5× left, and its realization
is the same at the two sizes at each budget.
"""

import math
import os
import sys
from decimal import Decimal

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import off_sample  # noqa: E402
from off_sample import T, DELTAS, load, digest, parse_solve, sci  # noqa: E402

LEFT = 1.5
NAMES = {
    "unit-off": "`unit / off` (0.12.0–0.15.0)",
    "measured-off": "`measured / off` (0.16.0's default)",
    "rss": "`--estimate rss`",
    "narrow": "`--narrow measured`",
    "heldout": "`--narrow heldout`",
    "rss-narrow": "`--estimate rss --narrow measured`",
    "rss-heldout": "`--estimate rss --narrow heldout`",
}
NEW = ("rss", "narrow", "heldout", "rss-narrow", "rss-heldout")


class Rows(off_sample.Rows):
    def judge_from(self, name, N, start):
        """In sample: windows 0 … N − 1. Out of sample: start … the last."""
        gap, dec, win = self.of(name)
        g_in = max(gap[: N * T])
        lo = start * T
        g_out = max(gap[lo:])
        pos = range(lo, self.n)
        flips = sum(1 for p in pos if dec[p] != self.top1[p])
        two = 2 * Decimal(repr(g_out))
        bound = sum(1 for p in pos if self.margin[p] < two)
        star = self.eps_star(start, self.windows)
        return {"in": g_in, "out": g_out, "ratio": g_out / g_in if g_in > 0 else math.inf, "flips": flips, "bound": bound,
                "n_out": self.n - lo, "cert": {d: g_out <= star[d] for d in DELTAS}, "star": star,
                "flips_in": sum(1 for p in range(N * T) if dec[p] != self.top1[p])}


def report(argv):
    import argparse
    ap = argparse.ArgumentParser(prog="spend.py report")
    ap.add_argument("out")
    ap.add_argument("--sizes", required=True)
    ap.add_argument("--budgets", required=True)
    ap.add_argument("--forms", required=True)
    ap.add_argument("--margin", type=float, default=2.5)
    a = ap.parse_args(argv)
    O = a.out
    sizes = [int(x) for x in a.sizes.split()]
    budgets = a.budgets.split()
    forms = a.forms.split()
    rows = Rows(os.path.join(O, "margins"))
    cell = {}
    for n in sizes:
        for b in budgets:
            for f in forms:
                stem = os.path.join(O, "solve", f"{n}-{b}-{f}")
                if not os.path.exists(stem + ".json"):
                    continue
                real = load(stem + ".json")
                sv = parse_solve(open(stem + ".txt").read())
                j = rows.judge_from(digest(real), n, 2 * n)
                cell[(n, b, f)] = {"real": real, "digest": digest(real), "solve": sv, "judge": j}
    p = print
    p("# Three ways to spend the budget, judged out of sample (D161)\n")
    p(f"Generated by `experiments/spend.py report {O}` from `experiments/spend.sh`'s outputs. The logits of the course GPT at "
      f"D = 64 on the trained weights; the envelope of the first N held-out windows; every realization run natively on the "
      f"{rows.windows} windows and judged in sample on the envelope's N and out of sample on windows 2N to {rows.windows - 1}, "
      f"which no form saw. The margin k = {a.margin}. Traffic is the solver's, one sample's (D158).\n")
    for b in budgets:
        bud = float(b)
        p(f"## At {b}\n")
        p("| form | N | traffic | measurements (narrowed, undone) | measured in sample | native in → out | out/in | out of sample, ÷ budget | flips out | #{m < 2ε} | cert. 10⁻³ | the realization |")
        p("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for f in forms:
            for n in sizes:
                c = cell.get((n, b, f))
                if not c:
                    p(f"| {NAMES.get(f, f)} | {n} | — | | | | | | | | | missing |")
                    continue
                s, j = c["solve"], c["judge"]
                steps = f" ({s['narrowed']}, {s['undone']})" if f not in ("unit-off", "measured-off", "rss") else ""
                p(f"| {NAMES.get(f, f)} | {n} | {s['baseline'] / s['bytes']:.3f}× | {s['measurements']}{steps} | {sci(s['measured'])} | "
                  f"{sci(j['in'])} → {sci(j['out'])} | {j['ratio']:.2f} | {j['out'] / bud:.2f} | {j['flips']} of {j['n_out']} | "
                  f"{j['bound']} | {'yes' if j['cert'][1e-3] else 'no'} | `{c['digest']}` |")
        p("")
    p("## The rule\n")
    p(f"A form is a default only if in every cell its gap out of sample is at most the budget ÷ {LEFT} and its realization "
      f"is the same at N = {' and '.join(map(str, sizes))} at each budget.\n")
    p("| form | holds with 1.5× left in every cell | the same realization at every size | passes |")
    p("|---|---|---|---|")
    passing = []
    for f in forms:
        cs = [cell.get((n, b, f)) for n in sizes for b in budgets]
        if any(c is None for c in cs):
            p(f"| {NAMES.get(f, f)} | a cell missing | | no |")
            continue
        left = all(cell[(n, b, f)]["judge"]["out"] <= float(b) / LEFT for n in sizes for b in budgets)
        worst = max(cell[(n, b, f)]["judge"]["out"] / float(b) for n in sizes for b in budgets)
        stable = all(len({cell[(n, b, f)]["digest"] for n in sizes}) == 1 for b in budgets)
        ok = left and stable
        if ok and f in NEW:
            passing.append(f)
        p(f"| {NAMES.get(f, f)} | {'yes' if left else 'no'} (at most {worst:.2f} of the budget) | {'yes' if stable else 'no'} | {'yes' if ok else 'no'} |")
    p("")
    if passing:
        def saved(f):
            return min(cell[(n, b, f)]["solve"]["baseline"] / cell[(n, b, f)]["solve"]["bytes"] for n in sizes for b in budgets)
        best = max(passing, key=lambda f: (saved(f), -sum(cell[(n, b, f)]["solve"]["measurements"] for n in sizes for b in budgets)))
        p(f"**Passing:** {', '.join(NAMES[f] for f in passing)}. By the plan's choice 7 (the most traffic saved, then the fewest "
          f"measurements), the candidate for the default is {NAMES[best]}.")
    else:
        p("**No new form passes the rule**: each stays a flag, and the default is `measured / off`.")


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    cmd, rest = sys.argv[1], sys.argv[2:]
    if cmd == "unique":
        off_sample.unique(rest[0], "")
    elif cmd == "report":
        report(rest)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
